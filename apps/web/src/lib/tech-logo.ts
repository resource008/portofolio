export function resolveTechLogo(name: string | null | undefined): string | null {
  const trimmed = (name ?? "").trim();
  if (!trimmed) return null;
  const key = trimmed.toLowerCase().replace(/[^a-z0-9]/g, "");
  if (!key) return null;
  const iconPath = TECH_MAP[key];
  if (iconPath) {
    return iconPath.startsWith("http") ? iconPath : `${DEVICON_BASE}${iconPath}.svg`;
  }
  return `${DEVICON_BASE}${key}/${key}-original.svg`;
}
